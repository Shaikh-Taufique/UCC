// Convert Urdu/Arabic digits (۰-۹, ٠-٩) and Devanagari digits (०-९) to ASCII 0-9
function normalizeNumerals(str) {
  if (!str) return '';
  return str
    .replace(/[۰٠०]/g, '0')
    .replace(/[۱١१]/g, '1')
    .replace(/[۲٢२]/g, '2')
    .replace(/[۳٣३]/g, '3')
    .replace(/[۴٤४]/g, '4')
    .replace(/[۵٥५]/g, '5')
    .replace(/[۶٦६]/g, '6')
    .replace(/[۷٧७]/g, '7')
    .replace(/[۸٨८]/g, '8')
    .replace(/[۹٩९]/g, '9');
}
window.normalizeNumerals = normalizeNumerals;

